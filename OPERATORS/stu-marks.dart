//4. Student Marks
//A student gets 75, 80, 85, and 90 marks. Calculate the total and average.

void main() {
  int mark1 = 75;
  int mark2 = 80;
  int mark3 = 85;
  int mark4 = 90;

  int total = mark1 + mark2 + mark3 + mark4;
  double average = total / 4;
  
  print("The total marks are $total");
  print("The average marks are $average");
}

